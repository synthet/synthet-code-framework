#!/usr/bin/env python3
"""Build (or check) the synthet-project-template repository from bootstrap.py.

The template is exactly what ``bootstrap.py`` seeds, with every project value left as its
``${PLACEHOLDER}``, plus ``init_project.py`` and ``TEMPLATE.md``. A repo created from the template
(GitHub "Use this template", or a plain copy) runs ``python init_project.py --name ...`` once and
ends up with the same files a direct bootstrap seed would have produced.

Usage:
    python scripts/build_project_template.py --target ../synthet-project-template
    python scripts/build_project_template.py --target ../synthet-project-template --check
"""

from __future__ import annotations

import argparse
import filecmp
import io
import json
import shutil
import sys
import tempfile
from contextlib import redirect_stdout
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

import bootstrap  # noqa: E402

VALUE_KEYS = ("PROJECT_NAME", "PROJECT_SLUG", "PROJECT_DESC", "REPO_URL", "STACK", "MCP_PREFIX",
              "BUILD_CMD", "TEST_CMD", "LINT_CMD", *bootstrap.BOARD_KEYS)
TEMPLATE_ONLY = ("init_project.py", "TEMPLATE.md")
IGNORED = {".git"}

INIT_SCRIPT = '''#!/usr/bin/env python3
"""Turn this synthet-project-template copy into a project: fill every ${{PLACEHOLDER}} once.

Generated by synthet-code-framework scripts/build_project_template.py. Do not edit by hand.

    python init_project.py --name "My App" --desc "One line" --stack python --repo-url https://github.com/me/my-app

The result matches `python bootstrap.py --target <dir> --backlog local-markdown` with the same options.
This script and TEMPLATE.md delete themselves afterwards unless --keep is given.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PLACEHOLDER_RE = re.compile(r"\\$\\{{([A-Z0-9_]+)\\}}")
STACK_DEFAULTS = {stack_defaults}
BOARD_KEYS = {board_keys}
TEXT_SUFFIXES = {text_suffixes}
TEXT_NAMES = {text_names}
TEMPLATE_ONLY = {template_only}


def slugify(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s or "project"


def values(a: argparse.Namespace) -> dict[str, str]:
    slug = a.slug or slugify(a.name)
    stack = a.stack if a.stack in STACK_DEFAULTS else "generic"
    vals = {{
        "PROJECT_NAME": a.name, "PROJECT_SLUG": slug, "PROJECT_DESC": a.desc or "TODO(PROJECT_DESC)",
        "REPO_URL": a.repo_url or "TODO(REPO_URL)", "STACK": stack, "MCP_PREFIX": a.mcp_prefix or slug,
        **STACK_DEFAULTS[stack],
    }}
    for key in BOARD_KEYS:
        vals[key] = f"TODO({{key}})"
    if a.board_url:
        vals["PROJECT_BOARD_URL"] = a.board_url
    if a.owner:
        vals["PROJECT_OWNER"] = a.owner
        vals["PROJECT_REPO"] = a.repo or slug
    return vals


def is_text(path: Path) -> bool:
    return path.suffix in TEXT_SUFFIXES or path.name in TEXT_NAMES


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument("--name", required=True, help="Project display name")
    ap.add_argument("--slug", help="Project slug (default: derived from name)")
    ap.add_argument("--desc", help="One-line description")
    ap.add_argument("--stack", default="generic", help="python|node|go|rust|generic")
    ap.add_argument("--repo-url", help="Git remote URL")
    ap.add_argument("--mcp-prefix", help="MCP server name prefix (default: slug)")
    ap.add_argument("--board-url", help="GitHub Project board URL")
    ap.add_argument("--owner", help="GitHub owner")
    ap.add_argument("--repo", help="GitHub repo name (default: slug)")
    ap.add_argument("--keep", action="store_true", help="Keep init_project.py and TEMPLATE.md")
    a = ap.parse_args(argv)
    vals = values(a)
    changed = 0
    for path in sorted(ROOT.rglob("*")):
        rel = path.relative_to(ROOT)
        if not path.is_file() or rel.parts[0] == ".git" or rel.as_posix() in TEMPLATE_ONLY or not is_text(path):
            continue
        text = path.read_text(encoding="utf-8")
        new = PLACEHOLDER_RE.sub(lambda m: vals.get(m.group(1), m.group(0)), text)
        if new != text:
            path.write_text(new, encoding="utf-8")
            changed += 1
    print(f"Filled placeholders in {{changed}} files for '{{vals['PROJECT_NAME']}}' (stack {{vals['STACK']}}).")
    if not a.keep:
        for name in TEMPLATE_ONLY:
            (ROOT / name).unlink(missing_ok=True)
    print("Next: fill build/test/lint commands if the stack defaults do not fit, then pick a backlog provider "
          "(agent-flow: `agent-flow init && agent-flow install --framework .`).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

TEMPLATE_MD = """# synthet-project-template

A ready-made copy of what [synthet-code-framework](https://github.com/synthet/synthet-code-framework)'s
`bootstrap.py` seeds, with every project value still a `${PLACEHOLDER}`. It is generated by the
framework's `scripts/build_project_template.py`; do not edit it by hand, change the framework instead.

## Start a project

1. Create a repository from this template (GitHub "Use this template"), or copy the folder.
2. Fill the placeholders once:

   ```bash
   python init_project.py --name "My App" --desc "One line" --stack python --repo-url https://github.com/me/my-app
   ```

   `--stack` is one of `python`, `node`, `go`, `rust`, `generic`. Optional: `--slug`, `--mcp-prefix`,
   `--owner`, `--repo`, `--board-url`. The script removes itself and this file afterwards.
3. Pick a backlog provider. With the agent-flow CLI installed:
   `agent-flow init && agent-flow install --framework .`

The result is the same as running `python bootstrap.py --target <dir> --backlog local-markdown` with
the same options. Use `bootstrap.py` directly for `--adopt`, `--auto-detect` or `--include-boilerplate`.
"""


def _render_init() -> str:
    return INIT_SCRIPT.format(
        stack_defaults=json.dumps(bootstrap.STACK_DEFAULTS, indent=4),
        board_keys=json.dumps(bootstrap.BOARD_KEYS),
        text_suffixes=repr(tuple(sorted(bootstrap.TEXT_SUFFIXES))),
        text_names=repr(("env.example", ".gitignore")),
        template_only=repr(TEMPLATE_ONLY),
    )


def build(target: Path) -> None:
    """Write the template into ``target`` (existing files are replaced, ``.git`` is kept)."""
    target.mkdir(parents=True, exist_ok=True)
    for child in target.iterdir():
        if child.name in IGNORED:
            continue
        shutil.rmtree(child) if child.is_dir() else child.unlink()
    original = bootstrap.build_values
    bootstrap.build_values = lambda _: {key: f"${{{key}}}" for key in VALUE_KEYS}
    argv = sys.argv
    sys.argv = ["bootstrap.py", "--target", str(target), "--name", "${PROJECT_NAME}", "--force",
                "--backlog", "local-markdown"]
    try:
        with redirect_stdout(io.StringIO()):
            code = bootstrap.main()
    finally:
        bootstrap.build_values = original
        sys.argv = argv
    if code != 0:
        raise SystemExit(f"bootstrap failed with exit code {code}")
    (target / "init_project.py").write_text(_render_init(), encoding="utf-8")
    (target / "TEMPLATE.md").write_text(TEMPLATE_MD, encoding="utf-8")


def diff_trees(expected: Path, actual: Path) -> list[str]:
    """Paths that differ between two trees, ignoring ``.git``."""
    out: list[str] = []

    def walk(rel: Path) -> None:
        cmp = filecmp.dircmp(expected / rel, actual / rel, ignore=list(IGNORED))
        out.extend(f"missing: {(rel / n).as_posix()}" for n in cmp.left_only)
        out.extend(f"extra: {(rel / n).as_posix()}" for n in cmp.right_only)
        _, mismatch, errors = filecmp.cmpfiles(expected / rel, actual / rel, cmp.common_files, shallow=False)
        out.extend(f"changed: {(rel / n).as_posix()}" for n in mismatch + errors)
        for sub in cmp.common_dirs:
            walk(rel / sub)

    walk(Path("."))
    return sorted(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument("--target", type=Path, required=True, help="synthet-project-template checkout")
    ap.add_argument("--check", action="store_true", help="Report drift instead of writing; exit 1 on drift")
    args = ap.parse_args(argv)
    target = args.target.resolve()
    if not args.check:
        build(target)
        files = sum(1 for p in target.rglob("*") if p.is_file() and ".git" not in p.relative_to(target).parts)
        print(f"Built template into {target} ({files} files).")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "template"
        build(fresh)
        drift = diff_trees(fresh, target) if target.is_dir() else ["missing: <target>"]
    if drift:
        print(f"Template drift in {target} ({len(drift)}):")
        for line in drift[:50]:
            print(f"  {line}")
        return 1
    print(f"Template in sync: {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
